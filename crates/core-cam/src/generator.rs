use crate::config::LaserProductionConfig;
use crate::operation::{LaserMode, LayerLaserSettings};
use crate::ordering::{optimize_cutting_order, CamContour};
use core_doc::Document;
use core_geom::Point2;

/// A single discrete toolpath segment ready for machining or preview.
#[derive(Debug, Clone, PartialEq)]
pub struct Toolpath {
    pub shape_id: u64,
    pub layer_name: String,
    pub mode: LaserMode,
    pub points: Vec<Point2>,
    pub closed: bool,
    pub speed_mm_s: f64,
    pub power_pct: f64,
    pub passes: u32,
    pub air_assist: bool,
    pub cut_length_mm: f64,
    pub sequence_index: usize,
}

/// A complete prepared laser machining job plan.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct CamJobPlan {
    pub toolpaths: Vec<Toolpath>,
    /// Laser-off rapid travel moves: (from_pt, to_pt)
    pub rapid_moves: Vec<(Point2, Point2)>,
    pub total_cut_length_mm: f64,
    pub total_rapid_length_mm: f64,
    pub estimated_duration_s: f64,
}

impl CamJobPlan {
    /// Generate standard G-Code for CNC laser cutters (GRBL, Marlin, Smoothie).
    pub fn export_gcode(&self) -> String {
        let mut out = String::with_capacity(8192);
        out.push_str("; VDraw Laser CAM Export - Standard G-Code\n");
        out.push_str("; Generated by VDraw pure-Rust CAM Engine\n");
        out.push_str(&format!(
            "; Total cut: {:.1} mm, Rapid travel: {:.1} mm, Est time: {:.1} s\n",
            self.total_cut_length_mm, self.total_rapid_length_mm, self.estimated_duration_s
        ));
        out.push_str("G21 ; Set units to millimeters\n");
        out.push_str("G90 ; Absolute positioning\n");
        out.push_str("M5  ; Laser OFF\n\n");

        for (i, tp) in self.toolpaths.iter().enumerate() {
            if tp.points.is_empty() {
                continue;
            }

            out.push_str(&format!(
                "; --- Sequence #{}: {} [{}] (Speed: {:.0} mm/s, Power: {:.0}%) ---\n",
                i + 1,
                tp.layer_name,
                tp.mode.label(),
                tp.speed_mm_s,
                tp.power_pct
            ));

            if tp.air_assist {
                out.push_str("M8  ; Air assist ON\n");
            } else {
                out.push_str("M9  ; Air assist OFF\n");
            }

            let start = tp.points[0];
            // Rapid move to start
            out.push_str(&format!("G0 X{:.3} Y{:.3}\n", start.x, start.y));

            // Laser ON with PWM power (0..1000 scale)
            let pwm = (tp.power_pct * 10.0).round().clamp(0.0, 1000.0) as u32;
            let feed_rate = (tp.speed_mm_s * 60.0).round(); // mm/min
            out.push_str(&format!("M3 S{}\n", pwm));

            // Linear cuts
            for pt in tp.points.iter().skip(1) {
                out.push_str(&format!("G1 X{:.3} Y{:.3} F{:.0}\n", pt.x, pt.y, feed_rate));
            }

            if tp.closed && tp.points.len() >= 3 {
                out.push_str(&format!(
                    "G1 X{:.3} Y{:.3} F{:.0}\n",
                    start.x, start.y, feed_rate
                ));
            }

            out.push_str("M5  ; Laser OFF\n\n");
        }

        out.push_str("; Return to home position\n");
        out.push_str("G0 X0 Y0\n");
        out.push_str("M9  ; Air assist OFF\n");
        out.push_str("M2  ; Program end\n");
        out
    }

    /// Generate HPGL / PLT format for vinyl plotters and standard laser systems.
    pub fn export_plt(&self) -> String {
        let mut out = String::with_capacity(4096);
        out.push_str("IN;\n"); // Initialize
        out.push_str("SP1;\n"); // Select pen 1

        // HPGL standard resolution is 40 units per mm (1016 DPI)
        let scale = 40.0;

        for tp in &self.toolpaths {
            if tp.points.is_empty() {
                continue;
            }
            let p0 = tp.points[0];
            out.push_str(&format!("PU{:.0},{:.0};\n", p0.x * scale, p0.y * scale)); // Pen up move

            for pt in tp.points.iter().skip(1) {
                out.push_str(&format!("PD{:.0},{:.0};\n", pt.x * scale, pt.y * scale));
                // Pen down cut
            }
            if tp.closed && tp.points.len() >= 3 {
                out.push_str(&format!("PD{:.0},{:.0};\n", p0.x * scale, p0.y * scale));
            }
            out.push_str("PU;\n");
        }

        out.push_str("SP0;\n"); // Pen park
        out
    }
}

/// Generate a production-ready machining plan from document geometry and laser settings.
pub fn generate_job_plan(doc: &Document, config: &LaserProductionConfig) -> CamJobPlan {
    let Some(page) = doc.active_page() else {
        return CamJobPlan::default();
    };

    let mut raw_contours = Vec::new();

    // 1. Extract contours from visible layers
    for layer in &page.layers {
        if !layer.visible {
            continue;
        }

        let settings = config
            .layer_settings
            .get(&layer.name)
            .cloned()
            .unwrap_or_else(|| {
                // Auto-classify layer by name (matching Corelith Studio rules)
                let name_lower = layer.name.to_lowercase();
                if name_lower.contains("engrave") || name_lower.contains("scan") {
                    LayerLaserSettings::new_engrave(180.0, 40.0, 1)
                } else if name_lower.contains("score") || name_lower.contains("mark") {
                    LayerLaserSettings::new_score(60.0, 30.0, 2)
                } else if name_lower.contains("guide") || name_lower.contains("ignore") {
                    LayerLaserSettings {
                        mode: LaserMode::Ignore,
                        ..Default::default()
                    }
                } else {
                    LayerLaserSettings::new_cut(25.0, 80.0, 0)
                }
            });

        if settings.mode == LaserMode::Ignore {
            continue;
        }

        for shape in &layer.shapes {
            let poly = shape.to_polycurve();
            let tolerance_mm = 0.05; // 0.05mm chord error bound for machine curves

            for subpath in &poly.subpaths {
                let local_pts = subpath.flatten(tolerance_mm);
                if local_pts.len() >= 2 {
                    let world_pts: Vec<Point2> = local_pts
                        .iter()
                        .map(|&p| shape.transform.transform_point(p))
                        .collect();
                    let contour = CamContour::new(
                        world_pts,
                        subpath.closed,
                        shape.id.0,
                        layer.name.clone(),
                        settings.mode,
                    );
                    raw_contours.push(contour);
                }
            }
        }
    }

    if raw_contours.is_empty() {
        return CamJobPlan::default();
    }

    // 2. Order toolpaths with containment & travel optimization
    let start_pt = Point2::new(config.start_x, config.start_y);
    let ordered_contours = optimize_cutting_order(
        raw_contours,
        start_pt,
        config.inside_out,
        config.optimize_order,
    );

    // 3. Assemble discrete toolpaths and rapid travel vectors
    let mut toolpaths = Vec::with_capacity(ordered_contours.len());
    let mut rapid_moves = Vec::new();
    let mut total_cut_len = 0.0;
    let mut total_rapid_len = 0.0;
    let mut est_time = 0.0;

    let mut current_pos = start_pt;

    for (seq_idx, c) in ordered_contours.into_iter().enumerate() {
        let settings = config
            .layer_settings
            .get(&c.layer_name)
            .cloned()
            .unwrap_or_else(|| LayerLaserSettings::new_cut(25.0, 80.0, 0));

        let cut_len = c.length_mm();
        total_cut_len += cut_len;

        // Rapid travel from current position to contour start
        let start_cut = c.points[0];
        let rapid_dist = current_pos.distance(start_cut);
        if rapid_dist > 0.01 {
            rapid_moves.push((current_pos, start_cut));
            total_rapid_len += rapid_dist;
            est_time += rapid_dist / config.rapid_speed_mm_s.max(10.0);
        }

        // Cut time = length / speed + pierce time allowance (0.05s per contour)
        est_time += (cut_len / settings.speed_mm_s.max(1.0)) * (settings.passes as f64) + 0.05;

        // Update current position to end of cut
        current_pos = if c.closed {
            c.points[0]
        } else {
            *c.points.last().unwrap()
        };

        toolpaths.push(Toolpath {
            shape_id: c.shape_id,
            layer_name: c.layer_name,
            mode: c.mode,
            points: c.points,
            closed: c.closed,
            speed_mm_s: settings.speed_mm_s,
            power_pct: settings.power_pct,
            passes: settings.passes,
            air_assist: settings.air_assist,
            cut_length_mm: cut_len,
            sequence_index: seq_idx + 1,
        });
    }

    CamJobPlan {
        toolpaths,
        rapid_moves,
        total_cut_length_mm: total_cut_len,
        total_rapid_length_mm: total_rapid_len,
        estimated_duration_s: est_time,
    }
}
